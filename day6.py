# comparison operators
# >,<,>=,<=
# it will return the value that it is true or not 
print(3>5)
print(3<5)
print(2<=2)
print(2<=5)
# one more thing ==(it shows the equal to) , !=(it shows the not equal to)
print(2==2)
print(2!=2)
# logical operators 
# or , and , not
stt1 = (3>5)
stt2 = (3<5)
# or logic tells us that if one of the values is true than it will gives us true
print(stt1 or stt2)
# (and) logic says that if both functions are true than it will return true value otherwise false
print(5==5 and (2==2))
# it will not return true value bcz one of them is not true value 
print(2!=2 and 5==5)
# not operators tells us about that value true  or false
# actually not does the opposite thing of what the statment is saying 
print(not 3>2)